// Helper to generate 24 hours of hourly telemetry with realistic diurnal cycles
export function generateStationTelemetry(
  stationId: string,
  baseTemp: number,
  baseHumidity: number,
  basePressure: number,
  baseWind: number,
  hasInjectedAnomaly?: { sensor: string; type: string; startHour: number }
): TelemetryPoint[] {
  const points: TelemetryPoint[] = [];
  const now = new Date();

  for (let i = 23; i >= 0; i--) {
    const time = new Date(now.getTime() - i * 3600 * 1000);
    const hour = time.getHours();
    const timeLabel = `${hour.toString().padStart(2, '0')}:00`;

    // Diurnal variation: peak temp around 14:00, min at 05:00
    const solarFactor = Math.max(0, Math.sin(((hour - 6) / 12) * Math.PI));
    const tempDiurnal = Math.sin(((hour - 9) / 12) * Math.PI) * 4.8;
    let temp = Number((baseTemp + tempDiurnal + (Math.random() * 0.6 - 0.3)).toFixed(1));

    // Inverse humidity relation
    let humidity = Math.min(100, Math.max(15, Math.round(baseHumidity - tempDiurnal * 3.2 + (Math.random() * 2 - 1))));

    // Barometric pressure semi-diurnal atmospheric tide
    let pressure = Number((basePressure + Math.sin(((hour - 3) / 6) * Math.PI) * 1.1 + (Math.random() * 0.3 - 0.15)).toFixed(1));

    // Wind: picking up in afternoon
    let windSpeed = Number((Math.max(0.2, baseWind + solarFactor * 4.2 + (Math.random() * 2 - 1))).toFixed(1));
    let windGust = Number((windSpeed + 3.2 + Math.random() * 3.5).toFixed(1));
    let windDirection = Math.round((210 + Math.sin(hour) * 45 + Math.random() * 15) % 360);

    // Solar radiation: 0 at night, up to 980 W/m² at solar noon
    let solarRadiation = Math.round(solarFactor * 920 * (1 - (100 - humidity) * 0.001) + (solarFactor > 0 ? Math.random() * 25 : 0));

    // Rainfall
    let rainfall = 0;
    if (baseHumidity > 80 && (hour >= 15 && hour <= 19)) {
      rainfall = Number((Math.random() * 6.5).toFixed(1));
    }

    // Soil moisture
    let soilMoisture = Math.min(65, Math.max(12, Math.round(32 + rainfall * 1.5 - (24 - i) * 0.15)));

    // Battery voltage: charges during daylight, drops slightly at night
    let batteryVoltage = Number((12.4 + solarFactor * 0.85 - (solarFactor === 0 ? 0.3 : 0) + (Math.random() * 0.04)).toFixed(2));
    let solarPanelWatts = Math.round(solarRadiation * 0.042 * 10) / 10;

    // Peer station ambient temp for spatial comparison
    const peerTemp = Number((temp + (Math.random() * 0.8 - 0.4)).toFixed(1));

    let hasAnomaly = false;
    let anomalyNote = undefined;

    // Apply specific anomalies based on station scenario
    if (hasInjectedAnomaly && i <= 24 - hasInjectedAnomaly.startHour) {
      if (hasInjectedAnomaly.sensor === 'temperature' && hasInjectedAnomaly.type === 'drift') {
        const driftAmount = ((24 - i - hasInjectedAnomaly.startHour) / (24 - hasInjectedAnomaly.startHour)) * 4.6;
        temp = Number((temp + driftAmount).toFixed(1));
        hasAnomaly = true;
        anomalyNote = 'Thermal radiation shield calibration drift';
      } else if (hasInjectedAnomaly.sensor === 'windSpeed' && hasInjectedAnomaly.type === 'flatline') {
        windSpeed = 0.0;
        windGust = 0.0;
        hasAnomaly = true;
        anomalyNote = 'Anemometer cup bearing freeze/seizure';
      } else if (hasInjectedAnomaly.sensor === 'humidity' && hasInjectedAnomaly.type === 'spike') {
        humidity = 107.5;
        hasAnomaly = true;
        anomalyNote = 'Thermodynamic boundary breach (>100% RH)';
      } else if (hasInjectedAnomaly.sensor === 'rainfall' && hasInjectedAnomaly.type === 'biofouling') {
        rainfall = 0.0;
        hasAnomaly = true;
        anomalyNote = 'Funnel clogged by leaves/debris during rain';
      } else if (hasInjectedAnomaly.sensor === 'batteryVoltage' && hasInjectedAnomaly.type === 'power_sag') {
        batteryVoltage = 10.7;
        hasAnomaly = true;
        anomalyNote = 'Marine salt crust on PV panel causing sag';
      }
    }

    points.push({
      timestamp: time.toISOString(),
      timeLabel,
      temperature: temp,
      humidity,
      pressure,
      windSpeed,
      windGust,
      windDirection,
      rainfall,
      solarRadiation,
      soilMoisture,
      batteryVoltage,
      solarPanelPower: solarPanelWatts,
      ambientTempPeer: peerTemp,
      hasAnomaly,
      anomalyNote,
    });
  }

  return points;
}

